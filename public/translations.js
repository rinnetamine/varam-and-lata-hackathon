let interfaceLanguage = 'lv';
try { interfaceLanguage = sessionStorage.getItem('interfaceLanguage') === 'en' ? 'en' : 'lv'; } catch {}
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const originalTitle = document.title;
function applyLanguage() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement.closest('script,style,[data-language-label]')) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const translation = englishTranslations[source.trim()];
    node.nodeValue = interfaceLanguage === 'en' && translation ? source.replace(source.trim(), translation) : source;
  }
  document.querySelectorAll('[aria-label],[placeholder],[alt]').forEach(element => {
    if (!originalAttributes.has(element)) originalAttributes.set(element, Object.fromEntries(['aria-label','placeholder','alt'].filter(name => element.hasAttribute(name)).map(name => [name, element.getAttribute(name)])));
    for (const [name, value] of Object.entries(originalAttributes.get(element))) element.setAttribute(name, interfaceLanguage === 'en' ? englishTranslations[value] || value : value);
  });
  document.documentElement.lang = interfaceLanguage;
  document.title = interfaceLanguage === 'en' ? englishTranslations[originalTitle] || originalTitle : originalTitle;
  document.querySelectorAll('[data-language-toggle]').forEach(button => {
    button.querySelector('[data-language-label]').textContent = interfaceLanguage === 'en' ? 'LV' : (button.classList.contains('language') ? 'English' : 'EN');
    button.setAttribute('aria-label', interfaceLanguage === 'en' ? 'Pārslēgties uz latviešu valodu' : 'Switch to English');
  });
}
function setTranslatedStatus(element, latvian) {
  element.textContent = latvian;
  applyLanguage();
}
document.querySelectorAll('[data-language-toggle]').forEach(button => button.addEventListener('click', () => {
  interfaceLanguage = interfaceLanguage === 'lv' ? 'en' : 'lv';
  try { sessionStorage.setItem('interfaceLanguage', interfaceLanguage); } catch {}
  applyLanguage();
}));
applyLanguage();
